// VeilTypes renders a kind's veil-types module: its Spec interface, FS,
// RenderHookContext, RenderHook, ValidateHook, and — when the graph indicates
// dependency relationships — the consumer-side `Dependency` union and/or
// per-consumer DependentHook types.
//
// When hostImport is "", the kind-independent host types
// (Std/Os/Fetch, File, Override/Metadata/Resource, ValidationIssue/Result,
// RegistryVariables) are inlined too — the standalone per-hook veil-types.ts.
// When hostImport is a module specifier (e.g. "./host"), those types are
// imported from it instead of inlined, so the module holds only this kind's
// types; the shared half is emitted once by HostTypes. The package form lets
// a shared-type change touch one file instead of every generated module.
func VeilTypes(k *config.Kind, variables map[string]*veilv1.Variable, graph *KindGraph, hostImport string) (string, error) {
	specInterface, err := specInterface(k)
	if err != nil {
		return "", err
	}
	specTypeName := PascalCase(k.Name) + "Spec"

	fsIface, err := fsInterface(k)
	if err != nil {
		return "", err
	}

	sourceTypes, _, err := SourceSchemaTypes(k, "")
	if err != nil {
		return "", err
	}

	node := graph.Node(k.Name)
	packageMode := hostImport != ""

	depTypes, err := dependencyTypes(node)
	if err != nil {
		return "", err
	}

	dependentTypes, err := dependentInterfaces(node, packageMode)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("// Generated by veil build — do not edit.\n\n")

	if hostImport != "" {
		// Package mode: import the kind-independent half from the shared
		// host module, emit only this kind's types.
		fmt.Fprintf(&b, "import type {\n"+
			"  File,\n  Std,\n  Os,\n  Fetch,\n  Resource,\n  ValidationResult,\n  RegistryVariables,\n"+
			"} from '%s';\n\n", hostImport)
		// Import each consumer kind's spec + FS from its own module rather than
		// replicating them, so a change to a widely-consumed spec regenerates
		// only that consumer's module, not every kind that depends on it.
		if imports := dependentSpecImports(node); imports != "" {
			b.WriteString(imports)
			b.WriteString("\n")
		}
		b.WriteString(specInterface)
		b.WriteString("\n")
		b.WriteString(fsIface)
		b.WriteString("\n")
		b.WriteString(sourceTypes)
		b.WriteString(depTypes)
		if depTypes != "" {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, renderHookContextTemplate, specTypeName)
		b.WriteString(hookInterface)
		b.WriteString("\n")
		b.WriteString(validateHookInterface)
		if dependentTypes != "" {
			b.WriteString("\n")
			b.WriteString(dependentTypes)
		}
		return b.String(), nil
	}

	// Inline mode: every type lives in this one file.
	varsIface, err := variablesInterface(variables)
	if err != nil {
		return "", err
	}
	b.WriteString(specInterface)
	b.WriteString("\n")
	b.WriteString(varsIface)
	b.WriteString("\n")
	b.WriteString(hostInterfaces)
	b.WriteString("\n")
	b.WriteString(fileInterface)
	b.WriteString("\n")
	b.WriteString(fsIface)
	b.WriteString("\n")
	b.WriteString(sourceTypes)
	b.WriteString(depTypes)
	if depTypes != "" {
		b.WriteString("\n")
	}
	b.WriteString(resourceTypes)
	b.WriteString("\n")
	fmt.Fprintf(&b, renderHookContextTemplate, specTypeName)
	b.WriteString(hookInterface)
	b.WriteString("\n")
	b.WriteString(validationResultTypes)
	b.WriteString("\n")
	b.WriteString(validateHookInterface)
	if dependentTypes != "" {
		b.WriteString("\n")
		b.WriteString(dependentTypes)
	}

	return b.String(), nil
}

// HostTypes renders the shared host-types module (written once as host.ts in
// the types package's output_dir): the kind-independent declarations every
// per-kind module imports — Std/Os/Fetch + YamlCodec/Stats, File,
// Override/Metadata/Resource, ValidationIssue/ValidationResult, and the
// project's RegistryVariables. The per-kind half is emitted by
// VeilTypes(..., hostImport).
func HostTypes(variables map[string]*veilv1.Variable) (string, error) {
	varsIface, err := variablesInterface(variables)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("// Generated by veil build — do not edit.\n\n")
	b.WriteString(hostInterfaces)
	b.WriteString("\n")
	b.WriteString(fileInterface)
	b.WriteString("\n")
	b.WriteString(resourceTypes)
	b.WriteString("\n")
	b.WriteString(validationResultTypes)
	b.WriteString("\n")
	b.WriteString(varsIface)
	return b.String(), nil
}

// resourceTypes declares the kind-independent resource envelope —
// Override, Metadata, and the generic Resource<Spec, Deps> — shared by
// every kind. Split from renderHookContextTemplate so the package types
// module can put these in host.ts and import them.
const resourceTypes = `export interface Override {
  /** Path of the source file in the kind being replaced. */
  source: string;
  /** Local path to the override file. */
  path: string;
}

export interface Metadata {
  /** Name of the kind this resource instantiates. */
  kind: string;
  /** Name of this resource. */
  name: string;
  /** Source files ejected for local override. */
  overrides?: Override[];
}

export interface Resource<Spec, Deps = never> {
  /** Standard metadata common to every resource. */
  metadata: Metadata;
  /** Resource-specific data, validated against the kind's schema and
   *  with any matching overlays already merged in. */
  spec: Spec;
  /** Declared dependencies on other resources. The Deps type
   *  parameter narrows the per-entry shape to the targets this kind
   *  is actually allowed to depend on. */
  dependencies?: Deps[];
}
`

// renderHookContextTemplate is the per-kind RenderHookContext interface, with
// a single %s placeholder for the kind's Spec type name. Split from
// resourceTypes so the package types module emits only this (importing
// Override/Metadata/Resource from host.ts).
const renderHookContextTemplate = `export interface RenderHookContext {
  /** The resource being rendered — full metadata + merged spec. */
  resource: Resource<%s, Dependency>;
  /** Path of the resource file being rendered, relative to the veil
   *  project root. Useful for hooks that need to locate sibling files
   *  (e.g. a service's package.json) by deriving paths from where the
   *  resource lives on disk. */
  path: string;
  /** Resolved input variables (from --var, env, or defaults). */
  vars: RegistryVariables;
  /** Absolute path of the veil project root — the directory housing
   *  veil.json. Provided for display / logging; std and os already
   *  resolve paths relative to this root. */
  root: string;
  /** Read-only file / env access. Paths resolve relative to the project
   *  root; use plain relative strings like "data.txt". */
  std: Std;
  /** Read-only filesystem inspection — list directories, stat, resolve
   *  symlinks. Paths resolve relative to the project root. */
  os: Os;
  /** Web Fetch-style HTTP client. Honors the host's allowlist, timeout,
   *  and response-size cap. */
  fetch: Fetch;
  /** Environment variables granted to this hook via its kind.json
   *  access.env declaration. Frozen — only the keys declared (and
   *  present on the host at render time) appear here. */
  env: Readonly<Record<string, string>>;
}

`

// HookTemplate renders the default scaffolded hook .ts. It imports FS,
// RenderHook, and RenderHookContext from typesImport — the sibling
// veil-types.ts (`./veil-types`) for inline kinds, or the shared types
// package specifier (e.g. `@platform/veil-types/service`) for kinds wired into
// generators.types — and exports a RenderHook with a placeholder `render`
// method.
func HookTemplate(hookName, typesImport string) string {
	var b strings.Builder

	b.WriteString("// Generated by veil — edit as needed.\n\n")
	fmt.Fprintf(&b, "import type { FS, RenderHook, RenderHookContext } from '%s';\n\n", typesImport)

	fnName := CamelCase(hookName)
	fmt.Fprintf(&b, "const %s: RenderHook = {\n", fnName)
	b.WriteString("  render(ctx: RenderHookContext, fs: FS): FS {\n")
	b.WriteString("    // TODO: implement\n")
	b.WriteString("    return fs;\n")
	b.WriteString("  },\n")
	b.WriteString("};\n\n")
	fmt.Fprintf(&b, "export default %s;\n", fnName)

	return b.String()
}

// ResourceSchema builds the composite JSON Schema for a kind and writes
// it to outPath. See ResourceSchemaBytes for the schema's shape.
func ResourceSchema(k *config.Kind, metadataSchema map[string]any, graph *KindGraph, outPath string) error {
	data, err := ResourceSchemaBytes(k, metadataSchema, graph)
	if err != nil {
		return err
	}
	return os.WriteFile(outPath, data, 0644)
}

// ResourceSchemaBytes is the byte-producing core of ResourceSchema: it
// builds the composite JSON Schema for a kind (metadata + spec envelope,
// plus a discriminated `dependencies` array when the kind has outgoing
// edges in the graph) and returns the marshalled bytes, so callers can
// persist it anywhere (disk, an in-memory FS, …).
func ResourceSchemaBytes(k *config.Kind, metadataSchema map[string]any, graph *KindGraph) ([]byte, error) {
	specSchema, err := LoadSpecSchema(k)
	if err != nil {
		return nil, err
	}

	delete(specSchema, "$schema")
	delete(specSchema, "$id")

	properties := map[string]any{
		"metadata": metadataSchema,
		"spec":     specSchema,
	}
	if dep := dependenciesProperty(graph.Node(k.Name)); dep != nil {
		properties["dependencies"] = dep
	}

	schema := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"type":                 "object",
		"additionalProperties": false,
		"title":                k.Name,
		"description":          fmt.Sprintf("Resource schema for kind %q.", k.Name),
		"required":             []string{"metadata", "spec"},
		"properties":           properties,
	}

	data, err := json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshalling schema: %w", err)
	}
	return data, nil
}

// LoadSpecSchema reads and parses the kind's schema file. Schema files
// may be authored in JSON or YAML — the extension on k.Schema decides
// how the bytes are parsed. If no schema is defined, returns a
// permissive object schema.
func LoadSpecSchema(k *config.Kind) (map[string]any, error) {
	if k.Schema == "" {
		return map[string]any{
			"type":        "object",
			"description": "Resource-specific configuration.",
		}, nil
	}

	schemaPath := k.Schema
	if !filepath.IsAbs(schemaPath) {
		schemaPath = filepath.Join(k.Dir, schemaPath)
	}

	var spec map[string]any
	if err := protoencode.ReadFile(schemaPath, &spec); err != nil {
		return nil, fmt.Errorf("reading schema %s: %w", schemaPath, err)
	}
	return spec, nil
}

// typeNameForSchemaPath derives a TS interface name from a schema file
// path: strip the extension and a trailing `.schema`, then PascalCase
// and prepend prefix (empty for a kind's own types; a consumer's
// PascalCase name when replicating cross-kind, so a dependent hook's
// replicated schema types can't collide with the target's own or
// another consumer's). "kubernetes_deployment.schema.json" with
// prefix "" -> "KubernetesDeployment"; with prefix "Service" ->
// "ServiceKubernetesDeployment".
func typeNameForSchemaPath(prefix, p string) string {
	base := filepath.Base(p)
	base = strings.TrimSuffix(base, filepath.Ext(base))
	base = strings.TrimSuffix(base, ".schema")
	return prefix + PascalCase(base)
}

// SourceSchemaTypes generates one TS interface per unique schema file a
// kind's sources reference (shared schemas share an interface), plus a
// source-path -> type-name map for typed FS accessors. Sources with no
// schema are absent from the map. Two schemas PascalCasing to the same
// name is a build-time error, same as fsInterfaceNamed's accessor guard.
func SourceSchemaTypes(k *config.Kind, prefix string) (string, map[string]string, error) {
	var b strings.Builder
	typeNameBySchema := make(map[string]string) // schema path -> type name
	nameOwner := make(map[string]string)        // type name -> first schema path that claimed it
	sourceTypeNames := make(map[string]string)  // source path -> type name

	defs := append([]*veilv1.SourceDefinition(nil), k.SourceDefs()...)
	sort.Slice(defs, func(i, j int) bool { return defs[i].GetPath() < defs[j].GetPath() })

	for _, def := range defs {
		schema := def.GetSchema()
		if schema == "" {
			continue
		}
		name, ok := typeNameBySchema[schema]
		if !ok {
			name = typeNameForSchemaPath(prefix, schema)
			if owner, taken := nameOwner[name]; taken && owner != schema {
				return "", nil, fmt.Errorf("schemas %q and %q both generate type name %q; rename one to disambiguate", owner, schema, name)
			}
			nameOwner[name] = schema
			typeNameBySchema[schema] = name

			schemaPath := schema
			if !filepath.IsAbs(schemaPath) {
				schemaPath = filepath.Join(k.Dir, schema)
			}
			var raw map[string]any
			if err := protoencode.ReadFile(schemaPath, &raw); err != nil {
				return "", nil, fmt.Errorf("reading schema %s: %w", schemaPath, err)
			}
			iface, err := interfaceFromSchemaMap(name, raw)
			if err != nil {
				return "", nil, fmt.Errorf("generating type for schema %s: %w", schema, err)
			}
			b.WriteString(iface)
			b.WriteString("\n")
		}
		sourceTypeNames[def.GetPath()] = name
	}
	return b.String(), sourceTypeNames, nil
}

// MethodSuffixForPath converts a declared source path into the PascalCase
// suffix used for its typed FS accessor. `./sources/my-file.yaml` →
// `SourcesMyFileYaml`. The companion JS implementation
// (__veilMethodSuffix in pkg/hook) must stay in lockstep — any change
// here needs to be mirrored there, or build-time types and runtime
// methods will drift.
func MethodSuffixForPath(p string) string {
	p = strings.TrimPrefix(p, "./")
	var b strings.Builder
	capitalize := true
	for _, c := range p {
		switch c {
		case '/', '.', '-', '_', ' ':
			capitalize = true
			continue
		}
		if capitalize {
			b.WriteRune(unicode.ToUpper(c))
			capitalize = false
		} else {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// PascalCase converts a kebab/snake name to PascalCase.
func PascalCase(s string) string {
	var b strings.Builder
	upper := true
	for _, c := range s {
		if c == '-' || c == '_' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(rune(strings.ToUpper(string(c))[0]))
			upper = false
		} else {
			b.WriteRune(c)
		}
	}
	return b.String()
}

// SplitImportSpecifier splits a bare module specifier into its package name
// and subpath: "@platform/veil-types/service" → ("@platform/veil-types",
// "service"); "pkg/sub/x" → ("pkg", "sub/x"); a bare package name yields an
// empty subpath. Used to derive the types package's name (and per-kind module
// path) from a kind's import.name.
func SplitImportSpecifier(spec string) (pkg, subpath string) {
	parts := strings.Split(spec, "/")
	n := 1
	if strings.HasPrefix(spec, "@") {
		n = 2
	}
	if len(parts) <= n {
		return spec, ""
	}
	return strings.Join(parts[:n], "/"), strings.Join(parts[n:], "/")
}

// CamelCase converts a kebab/snake name to camelCase.
func CamelCase(s string) string {
	pascal := PascalCase(s)
	if pascal == "" {
		return ""
	}
	return strings.ToLower(pascal[:1]) + pascal[1:]
}

